class GameObject:
    """Базовый класс для игровых объектов.

    Содержит общие атрибуты (позиция, цвет) и заготовку метода draw.
    """

    def __init__(self, position=None, body_color=None):
        """Инициализирует базовые атрибуты игрового объекта.

        Args:
            position: координаты верхнего левого угла объекта.
                По умолчанию — центральная точка экрана.
            body_color: цвет объекта в формате RGB.
        """
        if position is None:
            self.position = (SCREEN_WIDTH // 2, SCREEN_HEIGHT // 2)
        else:
            self.position = position
        self.body_color = body_color

    def draw(self):
        """Отрисовывает объект на игровом поле.

        Метод-заготовка, предназначенный для переопределения
        в дочерних классах.
        """
        pass

class Apple(GameObject):
    """Класс, описывающий яблоко и действия с ним."""

    def __init__(self):
        """Задаёт цвет яблока и устанавливает его начальную позицию."""
        super().__init__()
        self.body_color = APPLE_COLOR
        self.randomize_position()

    def randomize_position(self):
        """Устанавливает случайное положение яблока на игровом поле."""
        self.position = (
            randint(0, GRID_WIDTH - 1) * GRID_SIZE,
            randint(0, GRID_HEIGHT - 1) * GRID_SIZE,
        )

    def draw(self):
        """Отрисовывает яблоко на игровой поверхности."""
        rect = pygame.Rect(self.position, (GRID_SIZE, GRID_SIZE))
        pygame.draw.rect(screen, self.body_color, rect)
        pygame.draw.rect(screen, BORDER_COLOR, rect, 1)

